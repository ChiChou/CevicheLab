#!/usr/bin/env python3
"""Index external URLs recorded in versionable docs/code; never scan ignored data."""
import argparse
from collections import defaultdict
from pathlib import Path
import re
import subprocess
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
SUFFIXES = {'.md', '.py', '.swift', '.metal', '.cpp', '.sh'}

def render():
    names = subprocess.check_output(
        ['git', 'ls-files', '--cached', '--others', '--exclude-standard', '-z'],
        cwd=ROOT).decode().split('\0')
    refs = defaultdict(set)
    labels = {}
    for name in sorted(set(names)):
        path = ROOT / name
        if not name or name == 'REFERENCES.md' or path.suffix not in SUFFIXES or not path.is_file():
            continue
        for line in path.read_text().splitlines():
            for match in re.finditer(r"https?://[^\s<>\"'`{}]+", line):
                url = match[0].rstrip('.,;')
                # Markdown adds one outer parenthesis, but Apple API URLs may
                # contain their own balanced parentheses. Preserve those.
                while url.endswith(')') and url.count(')') > url.count('('):
                    url = url[:-1]
                parsed = urlsplit(url)
                if not parsed.netloc or parsed.netloc == 'ns.adobe.com':
                    continue
                if parsed.netloc == 'github.com' and parsed.path.startswith('/ChiChou/CevicheLab'):
                    continue
                refs[url].add(name)
                prefix = line[:match.start()]
                title = re.search(r'\[([^\[\]]+)\]\($', prefix)
                if title and url not in labels:
                    labels[url] = title[1].replace('`', '')
    groups = defaultdict(list)
    for url in sorted(refs):
        groups[urlsplit(url).netloc].append(url)
    lines = [
        '# Source reference index', '',
        'Generated by `python3 scripts/update_references.py`; check with `--check`.', '',
        f'This index contains **{len(refs)} distinct external source URLs** recorded in the versionable Markdown and source-code files. Each entry links back to the local documents or implementations that cite it. Ignored output folders, datasets, model weights, environments and external clones are not scanned. URLs are preserved, including recorded revisions and fragments; different pages within one project are separate references.', '',
        'Use [THIRD_PARTY_NOTICES.md](THIRD_PARTY_NOTICES.md) for authorship, exact component scope, license evidence and distinctions between included ports, separately executed tools/models, and research-only references. The detailed notes retain their review dates and limitations. This inventory does not claim that every referenced paper was implemented, every link remains available, or every artifact may be redistributed.', '',
    ]
    for host in sorted(groups):
        lines += [f'## {host}', '']
        for url in groups[host]:
            title = labels.get(url, urlsplit(url).path.lstrip('/') or host)
            title = title.replace('[', '(').replace(']', ')')
            local = ', '.join(f'[{name}]({name})' for name in sorted(refs[url]))
            lines += [f'- [{title}]({url}) — {local}']
        lines += ['']
    return '\n'.join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    target = ROOT / 'REFERENCES.md'
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit('REFERENCES.md is stale; run python3 scripts/update_references.py')
        print('Reference index is current')
    else:
        target.write_text(expected)
        print('Updated', target)

if __name__ == '__main__':
    main()
